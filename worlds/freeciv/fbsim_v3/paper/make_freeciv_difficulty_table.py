#!/usr/bin/env python
"""FreeCiv difficulty by question family and horizon, pooled over the 24 models (Appendix C).

    python data/freeciv/scripts/make_freeciv_difficulty_table.py

Input:  data/freeciv/family_horizon_scores.csv (model, set, family, horizon, excess, bits, ncrps, n)
Output: data/appendix_tables/freeciv_family_difficulty.tex
This is the first half of the retired data/make_difficulty_cost_tables.py (2026-09-16); the cost rows
that script also wrote are now edited in place by update_shared_tables.py.
"""
import pandas as pd

from _common import FAMILY_HORIZON, REPO, TABLES, rel

TABLES.mkdir(parents=True, exist_ok=True)
f = pd.read_csv(FAMILY_HORIZON)
print(f.set.unique(), f.model.nunique(), "models")
H = [90, 120, 150, 180, 210]
spec = {"bank": ("excess", "Mid-range: excess Brier score"), "tails": ("bits", "Tail set: excess bits"),
        "continuous": ("ncrps", "Continuous set: normalised CRPS")}
rows_out = []


def esc(s):
    return s.replace("_", "\\_")


out = TABLES / "freeciv_family_difficulty.tex"
with open(out, "w") as o:
    o.write("% Generated by data/freeciv/scripts/make_freeciv_difficulty_table.py from family_horizon_scores.csv; do not edit by hand.\n")
    o.write("\\begin{tabular}{@{}l r " + "r " * len(H) + "r@{}}\n\\toprule\nFamily & Items & " + " & ".join(f"T{h}" for h in H) + " & All \\\\\n")
    for s, (col, title) in spec.items():
        g = f[(f.set == s)]
        # per family x horizon: mean over models of the per-model mean (n identical across models)
        piv = g.groupby(["family", "horizon"])[col].mean().unstack("horizon").reindex(columns=H)
        n_items = g[g.model == g.model.iloc[0]].groupby("family")["n"].sum()
        # pooled over horizons, item-weighted
        gw = g.copy()
        gw["w"] = gw["n"] * gw[col]
        allc = gw.groupby("family").apply(lambda d: d["w"].sum() / d["n"].sum())
        piv["All"] = allc
        piv["Items"] = n_items
        piv = piv.sort_values("All", ascending=False)
        o.write("\\midrule\n\\multicolumn{%d}{@{}l}{\\emph{%s}} \\\\\n" % (len(H) + 3, title))
        for fam, r in piv.iterrows():
            cells = " & ".join("--" if pd.isna(r[h]) else f"{r[h]:.3f}" for h in H)
            o.write(f"{esc(fam)} & {int(r.Items)} & {cells} & {r['All']:.3f} \\\\\n")
            rows_out.append(dict(set=s, family=fam, items=int(r.Items), all=float(r["All"])))
        tot = gw.groupby("horizon").apply(lambda d: d["w"].sum() / d["n"].sum()).reindex(H)
        o.write("\\emph{all families} & %d & %s & %.3f \\\\\n" % (int(n_items.sum()), " & ".join(f"{v:.3f}" for v in tot), gw["w"].sum() / gw["n"].sum()))
    o.write("\\bottomrule\n\\end{tabular}\n")
print("wrote", rel(out))
for s in spec:
    r = [x for x in rows_out if x["set"] == s]
    print(s, "worst:", [(x["family"], round(x["all"], 3)) for x in r[:3]], "best:", [(x["family"], round(x["all"], 3)) for x in r[-2:]])
