#!/usr/bin/env python3
"""Train a LoRA/QLoRA SFT adapter for CivBench forecasting.

Designed for the 8B pilot on a single A100 80GB.

Input data format: JSONL prompt-completion records with fields:
  - prompt: str
  - completion: str

Generated by scripts/finetune/build_civbench_sft_dataset.py.
"""

from __future__ import annotations

import argparse
import inspect
import json
from pathlib import Path
from typing import Any

import torch
from datasets import load_dataset
from peft import LoraConfig, prepare_model_for_kbit_training
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    BitsAndBytesConfig,
    set_seed,
)
from trl import SFTConfig, SFTTrainer


def parse_target_modules(raw: str) -> str | list[str]:
    """Parse target modules argument."""
    value = raw.strip()
    if value == "all-linear":
        return value
    modules = [x.strip() for x in value.split(",") if x.strip()]
    if not modules:
        raise ValueError("--target-modules must be 'all-linear' or a comma-separated list")
    return modules


def parse_dtype(dtype_name: str) -> torch.dtype:
    """Convert string to torch dtype."""
    name = dtype_name.strip().lower()
    if name in {"bf16", "bfloat16"}:
        return torch.bfloat16
    if name in {"fp16", "float16", "half"}:
        return torch.float16
    if name in {"fp32", "float32"}:
        return torch.float32
    raise ValueError(f"Unsupported dtype: {dtype_name}")


def build_sft_config(args: argparse.Namespace, use_bf16: bool, has_eval: bool) -> SFTConfig:
    """Build SFTConfig with compatibility across TRL versions."""
    sig = inspect.signature(SFTConfig.__init__)
    valid = set(sig.parameters.keys())

    kwargs: dict[str, Any] = {
        "output_dir": str(args.output_dir),
        "run_name": args.run_name,
        "learning_rate": args.learning_rate,
        "lr_scheduler_type": args.lr_scheduler_type,
        "warmup_ratio": args.warmup_ratio,
        "num_train_epochs": args.num_train_epochs,
        "per_device_train_batch_size": args.per_device_train_batch_size,
        "per_device_eval_batch_size": args.per_device_eval_batch_size,
        "gradient_accumulation_steps": args.gradient_accumulation_steps,
        "logging_steps": args.logging_steps,
        "save_steps": args.save_steps,
        "eval_steps": args.eval_steps,
        "save_total_limit": args.save_total_limit,
        "seed": args.seed,
        "optim": args.optim,
        "gradient_checkpointing": args.gradient_checkpointing,
        "logging_first_step": True,
        "dataloader_num_workers": args.dataloader_num_workers,
    }

    # report_to accepts list in recent transformers/trl.
    if args.report_to == "none":
        kwargs["report_to"] = []
    else:
        kwargs["report_to"] = [args.report_to]

    # Mixed precision
    kwargs["bf16"] = bool(use_bf16)
    kwargs["fp16"] = not bool(use_bf16)

    # Strategy keys changed names in newer transformers.
    eval_strategy_value = "steps" if has_eval else "no"
    if "eval_strategy" in valid:
        kwargs["eval_strategy"] = eval_strategy_value
    elif "evaluation_strategy" in valid:
        kwargs["evaluation_strategy"] = eval_strategy_value

    if "save_strategy" in valid:
        kwargs["save_strategy"] = "steps"

    if has_eval:
        kwargs["load_best_model_at_end"] = True
        kwargs["metric_for_best_model"] = "eval_loss"
        kwargs["greater_is_better"] = False

    # Sequence length key changed across TRL versions.
    if "max_length" in valid:
        kwargs["max_length"] = args.max_length
    elif "max_seq_length" in valid:
        kwargs["max_seq_length"] = args.max_length

    if "packing" in valid:
        kwargs["packing"] = args.packing
    if "completion_only_loss" in valid:
        kwargs["completion_only_loss"] = True
    if "dataset_num_proc" in valid and args.dataset_num_proc is not None:
        kwargs["dataset_num_proc"] = args.dataset_num_proc

    # Keep only supported keys for current version.
    filtered = {k: v for k, v in kwargs.items() if k in valid}
    return SFTConfig(**filtered)


def normalize_prompt_completion_format(dataset, *, split_name: str, num_proc: int | None):
    """Normalize string prompt/completion records to conversational role/content format.

    Some TRL/transformers combinations route prompt-completion through chat templating,
    which expects conversational records. This keeps training robust across versions.
    """
    if "prompt" not in dataset.column_names or "completion" not in dataset.column_names:
        return dataset
    if len(dataset) == 0:
        return dataset

    sample = dataset[0]
    needs_prompt_conversion = isinstance(sample.get("prompt"), str)
    needs_completion_conversion = isinstance(sample.get("completion"), str)

    if not needs_prompt_conversion and not needs_completion_conversion:
        return dataset

    print(
        f"Normalizing {split_name} split to conversational prompt/completion format "
        f"(prompt_str={needs_prompt_conversion}, completion_str={needs_completion_conversion})"
    )

    def _convert(example: dict[str, Any]) -> dict[str, Any]:
        prompt_value = example.get("prompt")
        completion_value = example.get("completion")

        if isinstance(prompt_value, str):
            prompt_value = [{"role": "user", "content": prompt_value}]
        if isinstance(completion_value, str):
            completion_value = [{"role": "assistant", "content": completion_value}]

        return {"prompt": prompt_value, "completion": completion_value}

    return dataset.map(
        _convert,
        num_proc=num_proc if (num_proc is not None and num_proc > 1) else None,
        desc=f"Normalize {split_name} prompt/completion format",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Train LoRA/QLoRA SFT adapter for CivBench")
    parser.add_argument(
        "--model-id",
        type=str,
        default="meta-llama/Llama-3.1-8B-Instruct",
        help="Base model to fine-tune",
    )
    parser.add_argument(
        "--train-file",
        type=Path,
        required=True,
        help="Path to train JSONL (prompt/completion format)",
    )
    parser.add_argument(
        "--val-file",
        type=Path,
        default=None,
        help="Optional validation JSONL",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Output directory for adapter checkpoints",
    )
    parser.add_argument(
        "--run-name",
        type=str,
        default="civbench-lora-8b-pilot",
        help="Run name for logs",
    )

    # LoRA settings
    parser.add_argument("--lora-r", type=int, default=16)
    parser.add_argument("--lora-alpha", type=int, default=32)
    parser.add_argument("--lora-dropout", type=float, default=0.05)
    parser.add_argument(
        "--target-modules",
        type=str,
        default="all-linear",
        help="'all-linear' or comma-separated module names",
    )
    parser.add_argument("--use-rslora", action="store_true", help="Enable rank-stabilized LoRA")

    # Quantization
    parser.add_argument("--load-in-4bit", action="store_true", help="Use 4-bit QLoRA")
    parser.add_argument(
        "--bnb-compute-dtype",
        type=str,
        default="bfloat16",
        help="bitsandbytes compute dtype (bfloat16 or float16)",
    )
    parser.add_argument("--bnb-double-quant", action="store_true", help="Enable double quantization")
    parser.add_argument(
        "--bnb-quant-type",
        type=str,
        default="nf4",
        choices=["nf4", "fp4"],
        help="4-bit quantization type",
    )

    # Training
    parser.add_argument("--num-train-epochs", type=float, default=4.0)
    parser.add_argument("--learning-rate", type=float, default=2e-4)
    parser.add_argument("--lr-scheduler-type", type=str, default="cosine")
    parser.add_argument("--warmup-ratio", type=float, default=0.03)
    parser.add_argument("--max-length", type=int, default=4096)
    parser.add_argument("--packing", action="store_true", help="Enable sequence packing")
    parser.add_argument("--per-device-train-batch-size", type=int, default=2)
    parser.add_argument("--per-device-eval-batch-size", type=int, default=2)
    parser.add_argument("--gradient-accumulation-steps", type=int, default=8)
    parser.add_argument("--gradient-checkpointing", action="store_true")
    parser.add_argument("--optim", type=str, default="paged_adamw_8bit")
    parser.add_argument("--seed", type=int, default=42)

    # Runtime
    parser.add_argument(
        "--attn-implementation",
        type=str,
        default="sdpa",
        choices=["sdpa", "flash_attention_2", "eager"],
        help="Attention implementation",
    )
    parser.add_argument("--dataset-num-proc", type=int, default=4)
    parser.add_argument("--dataloader-num-workers", type=int, default=4)
    parser.add_argument("--logging-steps", type=int, default=10)
    parser.add_argument("--save-steps", type=int, default=100)
    parser.add_argument("--eval-steps", type=int, default=100)
    parser.add_argument("--save-total-limit", type=int, default=3)
    parser.add_argument(
        "--report-to",
        type=str,
        default="none",
        choices=["none", "wandb", "tensorboard"],
    )
    parser.add_argument(
        "--resume-from-checkpoint",
        type=str,
        default=None,
        help="Optional checkpoint path to resume from",
    )

    args = parser.parse_args()

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA GPU is required for this training script.")

    args.output_dir.mkdir(parents=True, exist_ok=True)

    set_seed(args.seed)

    print("Loading dataset...")
    data_files: dict[str, str] = {"train": str(args.train_file)}
    has_eval = args.val_file is not None and args.val_file.exists()
    if has_eval:
        data_files["validation"] = str(args.val_file)

    dataset = load_dataset("json", data_files=data_files)
    train_dataset = dataset["train"]
    eval_dataset = dataset["validation"] if has_eval else None

    train_dataset = normalize_prompt_completion_format(
        train_dataset,
        split_name="train",
        num_proc=args.dataset_num_proc,
    )
    if eval_dataset is not None:
        eval_dataset = normalize_prompt_completion_format(
            eval_dataset,
            split_name="validation",
            num_proc=args.dataset_num_proc,
        )

    print(f"Train examples: {len(train_dataset)}")
    if eval_dataset is not None:
        print(f"Validation examples: {len(eval_dataset)}")

    tokenizer = AutoTokenizer.from_pretrained(args.model_id, use_fast=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    bnb_compute_dtype = parse_dtype(args.bnb_compute_dtype)
    use_bf16 = bnb_compute_dtype == torch.bfloat16 and torch.cuda.is_bf16_supported()
    if bnb_compute_dtype == torch.bfloat16 and not use_bf16:
        print("bfloat16 requested but not supported on this GPU; falling back to float16")
        bnb_compute_dtype = torch.float16

    model_kwargs: dict[str, Any] = {
        "torch_dtype": bnb_compute_dtype,
        "attn_implementation": args.attn_implementation,
    }

    if args.load_in_4bit:
        model_kwargs["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_compute_dtype=bnb_compute_dtype,
            bnb_4bit_quant_type=args.bnb_quant_type,
            bnb_4bit_use_double_quant=args.bnb_double_quant,
        )

    print("Loading base model...")
    model = AutoModelForCausalLM.from_pretrained(args.model_id, **model_kwargs)

    if args.load_in_4bit:
        model = prepare_model_for_kbit_training(
            model,
            use_gradient_checkpointing=args.gradient_checkpointing,
        )

    model.config.use_cache = False

    target_modules = parse_target_modules(args.target_modules)
    lora_config = LoraConfig(
        r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=args.lora_dropout,
        target_modules=target_modules,
        bias="none",
        task_type="CAUSAL_LM",
        use_rslora=args.use_rslora,
    )

    sft_config = build_sft_config(args, use_bf16=use_bf16, has_eval=has_eval)

    trainer_kwargs: dict[str, Any] = {
        "model": model,
        "args": sft_config,
        "train_dataset": train_dataset,
        "eval_dataset": eval_dataset,
        "peft_config": lora_config,
    }
    trainer_sig = inspect.signature(SFTTrainer.__init__)
    if "processing_class" in trainer_sig.parameters:
        trainer_kwargs["processing_class"] = tokenizer
    else:
        trainer_kwargs["tokenizer"] = tokenizer

    trainer = SFTTrainer(**trainer_kwargs)

    print("Starting training...")
    train_result = trainer.train(resume_from_checkpoint=args.resume_from_checkpoint)

    print("Saving adapter and tokenizer...")
    trainer.save_model(str(args.output_dir))
    tokenizer.save_pretrained(str(args.output_dir))
    trainer.save_state()

    metrics = {"train": train_result.metrics}
    if has_eval:
        eval_metrics = trainer.evaluate()
        metrics["eval"] = eval_metrics

    with open(args.output_dir / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)

    run_config = vars(args).copy()
    run_config["train_examples"] = len(train_dataset)
    run_config["validation_examples"] = len(eval_dataset) if eval_dataset is not None else 0
    run_config["resolved_bf16"] = bool(use_bf16)
    run_config["resolved_compute_dtype"] = str(bnb_compute_dtype)
    run_config["resolved_target_modules"] = target_modules

    with open(args.output_dir / "run_config.json", "w") as f:
        json.dump(run_config, f, indent=2, default=str)

    print("Training complete")
    print(f"Adapter output: {args.output_dir}")


if __name__ == "__main__":
    main()
